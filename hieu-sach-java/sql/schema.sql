-- IF NOT EXISTS: khoi dong lai khong xoa du lieu.
CREATE TABLE IF NOT EXISTS CHUCH (
    TenChu VARCHAR(120) PRIMARY KEY, DiaChi VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS CHU_SDT (
    TenChu VARCHAR(120) REFERENCES CHUCH(TenChu), SDT VARCHAR(20), PRIMARY KEY(TenChu, SDT)
);
CREATE TABLE IF NOT EXISTS CUAHANG (
    TenCH VARCHAR(160) PRIMARY KEY, DiaChi VARCHAR(255) NOT NULL,
    TenChu VARCHAR(120) NOT NULL REFERENCES CHUCH(TenChu)
);
CREATE TABLE IF NOT EXISTS CUAHANG_SDT (
    TenCH VARCHAR(160) REFERENCES CUAHANG(TenCH), SDT VARCHAR(20), PRIMARY KEY(TenCH, SDT)
);
CREATE TABLE IF NOT EXISTS NHANVIEN (
    MaNV VARCHAR(30) PRIMARY KEY, Ten VARCHAR(120) NOT NULL, DiaChi VARCHAR(255),
    NgaySinh DATE, GioiTinh VARCHAR(20), NhiemVu VARCHAR(30) NOT NULL,
    CHECK(NhiemVu IN ('Bán hàng', 'Nhập hàng'))
);
CREATE TABLE IF NOT EXISTS NHANVIEN_SDT (
    MaNV VARCHAR(30) REFERENCES NHANVIEN(MaNV), SDT VARCHAR(20), PRIMARY KEY(MaNV, SDT)
);
CREATE TABLE IF NOT EXISTS LAM (
    MaNV VARCHAR(30) PRIMARY KEY REFERENCES NHANVIEN(MaNV),
    TenCH VARCHAR(160) NOT NULL REFERENCES CUAHANG(TenCH)
);
CREATE TABLE IF NOT EXISTS HANGHOA (
    MaHH VARCHAR(30) PRIMARY KEY, Ten VARCHAR(200) NOT NULL,
    Gia DECIMAL(14,0) NOT NULL CHECK(Gia >= 0),
    SoLuong INT NOT NULL CHECK(SoLuong >= 0),
    Loai VARCHAR(10) NOT NULL CHECK(Loai IN ('SACH', 'DUNGCU'))
);
CREATE TABLE IF NOT EXISTS DUNGCU (
    MaHHD VARCHAR(30) PRIMARY KEY REFERENCES HANGHOA(MaHH), Loai VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS SACH (
    MaHHS VARCHAR(30) PRIMARY KEY REFERENCES HANGHOA(MaHH),
    TacGia VARCHAR(160) NOT NULL, TheLoai VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS SACH_TB (
    MaHHS VARCHAR(30) REFERENCES SACH(MaHHS), TaiBan VARCHAR(80), PRIMARY KEY(MaHHS, TaiBan)
);
CREATE TABLE IF NOT EXISTS KHACHHANG (
    MaKH VARCHAR(30) PRIMARY KEY, Ten VARCHAR(120) NOT NULL, DiaChi VARCHAR(255),
    GioiTinh VARCHAR(20), NgaySinh DATE
);
CREATE TABLE IF NOT EXISTS KHACHHANG_SDT (
    MaKH VARCHAR(30) REFERENCES KHACHHANG(MaKH), SDT VARCHAR(20), PRIMARY KEY(MaKH, SDT)
);
CREATE TABLE IF NOT EXISTS NHACUNGCAP (
    MaCC VARCHAR(30) PRIMARY KEY, Ten VARCHAR(160) NOT NULL, DiaChi VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS NHACUNGCAP_SDT (
    MaCC VARCHAR(30) REFERENCES NHACUNGCAP(MaCC), SDT VARCHAR(20), PRIMARY KEY(MaCC, SDT)
);
CREATE TABLE IF NOT EXISTS CHINHANH (
    TenChiNhanh VARCHAR(120), MaCC VARCHAR(30) REFERENCES NHACUNGCAP(MaCC),
    DiaChi VARCHAR(255) NOT NULL, PRIMARY KEY(MaCC, TenChiNhanh)
);
-- Moi hoa don co 1 khach hang va 1 nhan vien; nhieu dong hang nam o BANHANG.
CREATE TABLE IF NOT EXISTS HOADONBAN (
    MaHDB VARCHAR(30) PRIMARY KEY, NgayBan DATE NOT NULL,
    MaNV VARCHAR(30) NOT NULL REFERENCES NHANVIEN(MaNV),
    MaKH VARCHAR(30) NOT NULL REFERENCES KHACHHANG(MaKH)
);
CREATE TABLE IF NOT EXISTS BANHANG (
    MaHDB VARCHAR(30) REFERENCES HOADONBAN(MaHDB), MaHH VARCHAR(30) REFERENCES HANGHOA(MaHH),
    SoLuong INT NOT NULL CHECK(SoLuong > 0), DonGiaBan DECIMAL(14,0) NOT NULL CHECK(DonGiaBan >= 0),
    PRIMARY KEY(MaHDB, MaHH)
);
CREATE TABLE IF NOT EXISTS HOADONNHAP (
    MaHDN VARCHAR(30) PRIMARY KEY, NgayNhap DATE NOT NULL,
    MaNV VARCHAR(30) NOT NULL REFERENCES NHANVIEN(MaNV),
    MaCC VARCHAR(30) NOT NULL, TenChiNhanh VARCHAR(120) NOT NULL,
    FOREIGN KEY(MaCC, TenChiNhanh) REFERENCES CHINHANH(MaCC, TenChiNhanh)
);
CREATE TABLE IF NOT EXISTS NHAPHANG (
    MaHDN VARCHAR(30) REFERENCES HOADONNHAP(MaHDN), MaHH VARCHAR(30) REFERENCES HANGHOA(MaHH),
    SoLuong INT NOT NULL CHECK(SoLuong > 0), DonGiaNhap DECIMAL(14,0) NOT NULL CHECK(DonGiaNhap >= 0),
    PRIMARY KEY(MaHDN, MaHH)
);
CREATE INDEX IF NOT EXISTS idx_hdb_ngay ON HOADONBAN(NgayBan);
CREATE INDEX IF NOT EXISTS idx_hdn_ngay ON HOADONNHAP(NgayNhap);
CREATE INDEX IF NOT EXISTS idx_bh_hang ON BANHANG(MaHH);
