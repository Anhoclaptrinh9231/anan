-- 11 bảng theo mô tả ERD-DATA DIAGRAM. PostgreSQL 16 / H2.
-- Schema bookstore_v2 độc lập; không xóa dữ liệu bản cũ.
-- ISBN được phép NULL theo quy tắc nghiệp vụ: duy nhất nếu cung cấp.
-- 1. Bảng CHI_NHANH
CREATE TABLE IF NOT EXISTS CHI_NHANH (
    MaCN VARCHAR(10) NOT NULL,
    TenCN VARCHAR(150) NOT NULL,
    DiaChi VARCHAR(255) NOT NULL,
    SoDienThoai VARCHAR(15) NOT NULL,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'Hoạt động',
    CONSTRAINT PK_CHI_NHANH PRIMARY KEY (MaCN),
    CONSTRAINT UQ_CHI_NHANH_SDT UNIQUE (SoDienThoai),
    CONSTRAINT CHK_CHI_NHANH_TT CHECK (TrangThai IN ('Hoạt động', 'Tạm ngừng'))
);

-- 2. Bảng NHAN_VIEN
CREATE TABLE IF NOT EXISTS NHAN_VIEN (
    MaNV VARCHAR(10) NOT NULL,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE NOT NULL,
    GioiTinh VARCHAR(10) CHECK (GioiTinh IN ('Nam', 'Nữ', 'Khác')),
    SoDienThoai VARCHAR(15) NOT NULL,
    ChucVu VARCHAR(50) NOT NULL,
    NgayVaoLam DATE NOT NULL DEFAULT CURRENT_DATE,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'Đang làm việc',
    MaCN VARCHAR(10) NOT NULL,
    CONSTRAINT PK_NHAN_VIEN PRIMARY KEY (MaNV),
    CONSTRAINT UQ_NHAN_VIEN_SDT UNIQUE (SoDienThoai),
    CONSTRAINT FK_NHANVIEN_CHINHANH FOREIGN KEY (MaCN) REFERENCES CHI_NHANH(MaCN),
    CONSTRAINT CHK_NHANVIEN_TT CHECK (TrangThai IN ('Đang làm việc', 'Tạm nghỉ', 'Đã nghỉ việc'))
);

-- 3. Bảng KHACH_HANG
CREATE TABLE IF NOT EXISTS KHACH_HANG (
    MaKH VARCHAR(10) NOT NULL,
    HoTen VARCHAR(100) NOT NULL,
    SoDienThoai VARCHAR(15) NOT NULL,
    Email VARCHAR(100),
    DiaChi VARCHAR(255),
    NgayDangKy DATE NOT NULL DEFAULT CURRENT_DATE,
    NgaySinh DATE,
    CONSTRAINT PK_KHACH_HANG PRIMARY KEY (MaKH),
    CONSTRAINT UQ_KHACH_HANG_SDT UNIQUE (SoDienThoai)
);

-- 4. Bảng THE_LOAI
CREATE TABLE IF NOT EXISTS THE_LOAI (
    MaTL VARCHAR(10) NOT NULL,
    TenTheLoai VARCHAR(100) NOT NULL,
    MoTa VARCHAR(255),
    CONSTRAINT PK_THE_LOAI PRIMARY KEY (MaTL),
    CONSTRAINT UQ_THE_LOAI_TEN UNIQUE (TenTheLoai)
);

-- 5. Bảng SACH
CREATE TABLE IF NOT EXISTS SACH (
    MaSach VARCHAR(15) NOT NULL,
    ISBN VARCHAR(20),
    TenSach VARCHAR(200) NOT NULL,
    TacGia VARCHAR(150) NOT NULL,
    NhaXuatBan VARCHAR(150) NOT NULL,
    NamXuatBan INT CHECK (NamXuatBan >= 1900),
    DonGiaBan DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (DonGiaBan >= 0),
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'Đang kinh doanh',
    MaTL VARCHAR(10) NOT NULL,
    DaXoa BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_SACH PRIMARY KEY (MaSach),
    CONSTRAINT UQ_SACH_ISBN UNIQUE (ISBN),
    CONSTRAINT FK_SACH_THELOAI FOREIGN KEY (MaTL) REFERENCES THE_LOAI(MaTL),
    CONSTRAINT CHK_SACH_TT CHECK (TrangThai IN ('Đang kinh doanh', 'Ngừng kinh doanh'))
);

-- 6. Bảng NHA_CUNG_CAP
CREATE TABLE IF NOT EXISTS NHA_CUNG_CAP (
    MaNCC VARCHAR(10) NOT NULL,
    TenNCC VARCHAR(150) NOT NULL,
    DiaChi VARCHAR(255) NOT NULL,
    SoDienThoai VARCHAR(15) NOT NULL,
    Email VARCHAR(100),
    CONSTRAINT PK_NHA_CUNG_CAP PRIMARY KEY (MaNCC),
    CONSTRAINT UQ_NCC_SDT UNIQUE (SoDienThoai)
);

-- 7. Bảng PHIEU_NHAP
CREATE TABLE IF NOT EXISTS PHIEU_NHAP (
    MaPN VARCHAR(15) NOT NULL,
    NgayNhap TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'Đã xác nhận',
    MaNCC VARCHAR(10) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    MaCN VARCHAR(10) NOT NULL,
    CONSTRAINT PK_PHIEU_NHAP PRIMARY KEY (MaPN),
    CONSTRAINT FK_PN_NCC FOREIGN KEY (MaNCC) REFERENCES NHA_CUNG_CAP(MaNCC),
    CONSTRAINT FK_PN_NHANVIEN FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV),
    CONSTRAINT FK_PN_CHINHANH FOREIGN KEY (MaCN) REFERENCES CHI_NHANH(MaCN),
    CONSTRAINT CHK_PN_TT CHECK (TrangThai IN ('Chờ xác nhận', 'Đã xác nhận', 'Đã hủy'))
);

-- 8. Bảng CT_PHIEU_NHAP
CREATE TABLE IF NOT EXISTS CT_PHIEU_NHAP (
    MaPN VARCHAR(15) NOT NULL,
    MaSach VARCHAR(15) NOT NULL,
    SoLuongNhap INT NOT NULL CHECK (SoLuongNhap > 0),
    DonGiaNhap DECIMAL(12,2) NOT NULL CHECK (DonGiaNhap >= 0),
    CONSTRAINT PK_CT_PHIEU_NHAP PRIMARY KEY (MaPN, MaSach),
    CONSTRAINT FK_CTPN_PHIEUNHAP FOREIGN KEY (MaPN) REFERENCES PHIEU_NHAP(MaPN) ON DELETE CASCADE,
    CONSTRAINT FK_CTPN_SACH FOREIGN KEY (MaSach) REFERENCES SACH(MaSach)
);

-- 9. Bảng HOA_DON_BAN
CREATE TABLE IF NOT EXISTS HOA_DON_BAN (
    MaHDB VARCHAR(15) NOT NULL,
    NgayBan TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'Hoàn tất',
    PhuongThucThanhToan VARCHAR(50) NOT NULL DEFAULT 'Tiền mặt',
    MaNV VARCHAR(10) NOT NULL,
    MaCN VARCHAR(10) NOT NULL,
    MaKH VARCHAR(10) NULL,
    CONSTRAINT PK_HOA_DON_BAN PRIMARY KEY (MaHDB),
    CONSTRAINT FK_HDB_NHANVIEN FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV),
    CONSTRAINT FK_HDB_CHINHANH FOREIGN KEY (MaCN) REFERENCES CHI_NHANH(MaCN),
    CONSTRAINT FK_HDB_KHACHHANG FOREIGN KEY (MaKH) REFERENCES KHACH_HANG(MaKH) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT CHK_HDB_TT CHECK (TrangThai IN ('Chờ xử lý', 'Hoàn tất', 'Đã hủy')),
    CONSTRAINT CHK_HDB_PTTT CHECK (PhuongThucThanhToan IN ('Tiền mặt', 'Chuyển khoản', 'Thẻ'))
);

-- 10. Bảng CT_HOA_DON_BAN
CREATE TABLE IF NOT EXISTS CT_HOA_DON_BAN (
    MaHDB VARCHAR(15) NOT NULL,
    MaSach VARCHAR(15) NOT NULL,
    SoLuongBan INT NOT NULL CHECK (SoLuongBan > 0),
    DonGiaBanThucTe DECIMAL(12,2) NOT NULL CHECK (DonGiaBanThucTe >= 0),
    CONSTRAINT PK_CT_HOA_DON_BAN PRIMARY KEY (MaHDB, MaSach),
    CONSTRAINT FK_CTHDB_HOADON FOREIGN KEY (MaHDB) REFERENCES HOA_DON_BAN(MaHDB) ON DELETE CASCADE,
    CONSTRAINT FK_CTHDB_SACH FOREIGN KEY (MaSach) REFERENCES SACH(MaSach)
);

-- 11. Bảng TON_KHO
CREATE TABLE IF NOT EXISTS TON_KHO (
    MaCN VARCHAR(10) NOT NULL,
    MaSach VARCHAR(15) NOT NULL,
    SoLuongTon INT NOT NULL DEFAULT 0 CHECK (SoLuongTon >= 0),
    CONSTRAINT PK_TON_KHO PRIMARY KEY (MaCN, MaSach),
    CONSTRAINT FK_TONKHO_CHINHANH FOREIGN KEY (MaCN) REFERENCES CHI_NHANH(MaCN),
    CONSTRAINT FK_TONKHO_SACH FOREIGN KEY (MaSach) REFERENCES SACH(MaSach)
);
CREATE OR REPLACE VIEW V_BAO_CAO_DOANH_THU_CHI_NHANH AS
SELECT CN.MaCN,
       CN.TenCN,
       COUNT(DISTINCT HDB.MaHDB) AS SoHoaDonHoanTat,
       SUM(CTB.SoLuongBan) AS TongSoLuongSachBan,
       SUM(CTB.SoLuongBan * CTB.DonGiaBanThucTe) AS TongDoanhThu
FROM CHI_NHANH CN
LEFT JOIN HOA_DON_BAN HDB ON CN.MaCN = HDB.MaCN AND HDB.TrangThai = 'Hoàn tất'
LEFT JOIN CT_HOA_DON_BAN CTB ON HDB.MaHDB = CTB.MaHDB
GROUP BY CN.MaCN, CN.TenCN;

-- 2. Tạo View thống kê Chi phí nhập hàng theo Chi nhánh (Chỉ tính phiếu nhập 'Đã xác nhận'):
CREATE OR REPLACE VIEW V_BAO_CAO_CHI_PHI_NHAP_CHI_NHANH AS
SELECT CN.MaCN,
       CN.TenCN,
       COUNT(DISTINCT PN.MaPN) AS SoPhieuNhapXacNhan,
       SUM(CTN.SoLuongNhap) AS TongSoLuongSachNhap,
       SUM(CTN.SoLuongNhap * CTN.DonGiaNhap) AS TongChiPhiNhap
FROM CHI_NHANH CN
LEFT JOIN PHIEU_NHAP PN ON CN.MaCN = PN.MaCN AND PN.TrangThai = 'Đã xác nhận'
LEFT JOIN CT_PHIEU_NHAP CTN ON PN.MaPN = CTN.MaPN
GROUP BY CN.MaCN, CN.TenCN;
